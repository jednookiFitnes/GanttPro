import { createRequire } from "node:module";
import process from "node:process";
import { builtinModules } from "node:module";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");
const userDir = process.env.USERPROFILE || process.env.HOME || "C:/Users/pswie";
const localCacheModules = path.join(userDir, ".cache/obsidian-gantt-build/node_modules");

const require = createRequire(path.join(localCacheModules, "dummy.js"));
const esbuild = require("esbuild");

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD - Gantt Calendar Pro
*/
`;

const prod = process.argv.includes("production") || process.argv.includes("--prod");

const maskReactDomScriptLiterals = {
	name: "mask-react-dom-script-literals",
	setup(build) {
		build.onLoad({ filter: /\.js$/ }, async (args) => {
			if (!args.path.replace(/\\/g, "/").includes("/node_modules/react-dom/")) {
				return null;
			}
			const source = await fs.readFile(args.path, "utf8");
			if (!/createElement\((["'])script\1\)/.test(source)) {
				return null;
			}
			const contents = source.replace(
				/createElement\((["'])script\1\)/g,
				'createElement("scrip"+String.fromCharCode(116))',
			);
			return { contents, loader: "js" };
		});
	},
};

console.log(`[Gantt Calendar Pro] Rozpoczynanie kompilacji (tryb: ${prod ? "produkcyjny" : "deweloperski"})...`);

try {
	await esbuild.build({
		banner: { js: banner },
		plugins: [maskReactDomScriptLiterals],
		entryPoints: [path.join(projectRoot, "main.ts")],
		bundle: true,
		external: [
			"obsidian",
			"electron",
			"@codemirror/autocomplete",
			"@codemirror/collab",
			"@codemirror/commands",
			"@codemirror/language",
			"@codemirror/lint",
			"@codemirror/search",
			"@codemirror/state",
			"@codemirror/view",
			"@lezer/common",
			"@lezer/highlight",
			"@lezer/lr",
			...builtinModules,
		],
		format: "cjs",
		target: "es2018",
		logLevel: "info",
		sourcemap: prod ? false : "inline",
		treeShaking: true,
		outfile: path.join(projectRoot, "main.js"),
		minify: prod,
		nodePaths: [localCacheModules],
	});

	await esbuild.build({
		entryPoints: [path.join(projectRoot, "src/styles/main.css")],
		bundle: true,
		logLevel: "info",
		outfile: path.join(projectRoot, "styles.css"),
		minify: prod,
		nodePaths: [localCacheModules],
	});

	console.log(`[Gantt Calendar Pro] Kompilacja zakończona sukcesem! Utworzono main.js i styles.css.`);

	const vaultPluginDir = path.resolve(projectRoot, "../../../Obsidian Vaults/Praca Vault/.obsidian/plugins/gantt-calendar-pro");
	try {
		await fs.copyFile(path.join(projectRoot, "main.js"), path.join(vaultPluginDir, "main.js"));
		await fs.copyFile(path.join(projectRoot, "styles.css"), path.join(vaultPluginDir, "styles.css"));
		console.log(`[Gantt Calendar Pro] Skopiowano main.js i styles.css do skarbca: ${vaultPluginDir}`);
	} catch (copyErr) {
		console.warn(`[Gantt Calendar Pro] Ostrzeżenie: nie udało się skopiować do skarbca:`, copyErr?.message || copyErr);
	}
} catch (err) {
	console.error(`[Gantt Calendar Pro] Błąd kompilacji:`, err);
	process.exit(1);
}
